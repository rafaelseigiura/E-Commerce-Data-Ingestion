WITH order_items AS (

SELECT
    A.ORDER_ID,
    A.PRODUCT_ID,
    B.PRODUCT_CATEGORY_NAME,
    COUNT(*) AS QTD_ITENS,
    SUM(B.PRODUCT_WEIGHT_G) AS PESO_TOTAL_G,
    SUM(
        B.PRODUCT_WIDTH_CM
        * B.PRODUCT_HEIGHT_CM
        * B.PRODUCT_LENGTH_CM
    )/1000 AS VOLUME_TOTAL_Litros,
    SUM(A.PRICE) AS VALOR_TOTAL,
    SUM(A.FREIGHT_VALUE) AS FRETE_TOTAL

FROM SILVER.STG_ORDERS_ITEMS A

LEFT JOIN SILVER.STG_PRODUCTS B
    ON A.PRODUCT_ID = B.PRODUCT_ID

LEFT JOIN SILVER.STG_ORDERS C
    ON A.ORDER_ID = C.ORDER_ID

GROUP BY
    A.ORDER_ID,
    A.PRODUCT_ID,
    B.PRODUCT_CATEGORY_NAME
)

SELECT *
FROM order_items