-- intermediate orders
SELECT
	A.ORDER_ID,
	c.customer_id,
	D.CUSTOMER_UNIQUE_ID,
	C.ORDER_STATUS,
	COUNT(A.ORDER_ID) QTD_ITENS,
	SUM(PRICE) VALOR_TOTAL,
	SUM(FREIGHT_VALUE) FRETE_TOTAL,
	--(C.DELIVERED_CUSTOMER_DATE - PURCHASE_TIMESTAMP) AS DIAS_ENTREGA,
	GREATEST(
		0,
		EXTRACT(
			DAY
			FROM
				(
					DELIVERED_CUSTOMER_DATE - C.ESTIMATED_DELIVERY_DATE
				)
		)
	) AS DIAS_ATRASO
FROM
	SILVER.STG_ORDERS_ITEMS A
	LEFT JOIN SILVER.STG_ORDERS C ON A.ORDER_ID = C.ORDER_ID
	LEFT JOIN SILVER.STG_CUSTOMER D ON C.customer_id = D.customer_id
GROUP BY
	A.ORDER_ID,
	c.customer_id,
	D.CUSTOMER_UNIQUE_ID,
	C.ORDER_STATUS,
	GREATEST(
		0,
		EXTRACT(
			DAY
			FROM
				(
					DELIVERED_CUSTOMER_DATE - C.ESTIMATED_DELIVERY_DATE
				)
		)
	)